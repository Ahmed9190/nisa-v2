export function stripHtml(html: string): string {
  return html
    .replace(/&nbsp;/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const ALLOWED_TAGS = new Set([
  'H1',
  'H2',
  'H3',
  'H4',
  'P',
  'BR',
  'STRONG',
  'B',
  'EM',
  'I',
  'U',
  'UL',
  'OL',
  'LI',
  'BLOCKQUOTE',
  'A',
]);

export function sanitizeRichHtml(rawHtml: string): string {
  const normalized = (rawHtml || '').replace(/&nbsp;|\u00a0/g, ' ').trim();
  if (!normalized) return '';
  if (typeof DOMParser === 'undefined') return normalized;

  const doc = new DOMParser().parseFromString(normalized, 'text/html');
  const walk = (node: Node): string => {
    if (node.nodeType === Node.TEXT_NODE) {
      return (node.textContent || '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;');
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return '';
    const el = node as HTMLElement;
    const tag = el.tagName.toUpperCase();
    if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'IFRAME') return '';

    const childrenHtml = Array.from(el.childNodes).map(walk).join('');
    if (!ALLOWED_TAGS.has(tag)) return childrenHtml;

    const lower = tag.toLowerCase();
    if (lower === 'br') return '<br />';
    if (lower === 'a') {
      const href = el.getAttribute('href') || '';
      const safe =
        href.startsWith('http://') ||
        href.startsWith('https://') ||
        href.startsWith('/') ||
        href.startsWith('mailto:') ||
        href.startsWith('tel:');
      if (!safe) return childrenHtml;
      const escapedHref = href.replace(/"/g, '&quot;');
      return `<a href="${escapedHref}" target="_blank" rel="noopener noreferrer">${childrenHtml}</a>`;
    }
    return `<${lower}>${childrenHtml}</${lower}>`;
  };

  return Array.from(doc.body.childNodes).map(walk).join('');
}

export function matchCategorySlug(productCategoryName: string, filterSlug: string): boolean {
  if (!filterSlug) return true;
  const norm = (s: string) =>
    s
      .toLowerCase()
      .replace(/[İı]/g, 'i')
      .replace(/[ğ]/g, 'g')
      .replace(/[ü]/g, 'u')
      .replace(/[ş]/g, 's')
      .replace(/[ö]/g, 'o')
      .replace(/[ç]/g, 'c')
      .replace(/[^a-z0-9]/g, '');

  const pNorm = norm(productCategoryName);
  const fNorm = norm(filterSlug);

  // Match aliases between collection URLs and category names (e.g. miras-collection-s26 / rzgr-collection-s25 / dou-collection-s25)
  if (fNorm.includes('miras') && pNorm.includes('miras')) return true;
  if ((fNorm.includes('rzgr') || fNorm.includes('ruzgar')) && pNorm.includes('ruzgar')) return true;
  if ((fNorm.includes('dou') || fNorm.includes('dogus')) && pNorm.includes('dogus')) return true;
  if (fNorm.includes('toprak') && pNorm.includes('toprak')) return true;
  if (fNorm.includes('endofseason') && pNorm.includes('endofseason')) return true;

  return pNorm.includes(fNorm) || fNorm.includes(pNorm);
}
